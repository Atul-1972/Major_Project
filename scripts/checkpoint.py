"""Persist development context using only the Python standard library."""

from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
STATE_DIR = ROOT / ".project"
STATE_FILE = STATE_DIR / "state.json"
HISTORY_FILE = STATE_DIR / "history.jsonl"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--summary", required=True, help="Work saved and checks performed")
    parser.add_argument("--next", required=True, dest="next_action", help="Concrete next action")
    parser.add_argument("--phase", help="Approved phase; otherwise keep the previous phase")
    parser.add_argument(
        "--status",
        choices=["in_progress", "awaiting_requirements", "awaiting_approval", "paused", "complete"],
        help="Otherwise keep the previous status",
    )
    parser.add_argument("--completed", action="append", default=[], help="Completed item; repeatable")
    args = parser.parse_args()
    if not args.summary.strip() or not args.next_action.strip():
        parser.error("Summary and next action must contain text.")

    STATE_DIR.mkdir(parents=True, exist_ok=True)
    previous = json.loads(STATE_FILE.read_text(encoding="utf-8")) if STATE_FILE.exists() else {}
    # Read existing history before writing, so a malformed log is never overwritten.
    history = []
    if HISTORY_FILE.exists():
        history = [json.loads(line) for line in HISTORY_FILE.read_text(encoding="utf-8").splitlines() if line.strip()]
    completed = list(dict.fromkeys(previous.get("completed", []) + args.completed))
    state = {
        "schema_version": 1,
        "project": "SkinDiseaseAI",
        "updated_at": datetime.now(timezone.utc).isoformat(),
        "phase": args.phase or previous.get("phase", "preparation"),
        "status": args.status or previous.get("status", "awaiting_approval"),
        "summary": args.summary.strip(),
        "next_action": args.next_action.strip(),
        "completed": completed,
    }
    event = {**state, "newly_completed": args.completed}
    with HISTORY_FILE.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(event, ensure_ascii=False) + "\n")
        handle.flush()
        os.fsync(handle.fileno())
    temporary = STATE_FILE.with_suffix(".json.tmp")
    with temporary.open("w", encoding="utf-8") as handle:
        handle.write(json.dumps(state, indent=2, ensure_ascii=False) + "\n")
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(temporary, STATE_FILE)

    history.append(event)
    lines = ["# Development progress", "", "Generated by `scripts/checkpoint.py`; timestamps use UTC.", ""]
    for entry in history:
        lines.extend([
            f"## {entry['updated_at']} — {entry['phase']}", "",
            f"Status: {entry['status']}", "", entry["summary"], "",
        ])
        if entry.get("newly_completed"):
            lines.extend(f"- {item}" for item in entry["newly_completed"])
            lines.append("")
        lines.extend([f"Next action: {entry['next_action']}", ""])
    report = ROOT / "docs" / "PROGRESS.md"
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text("\n".join(lines), encoding="utf-8")
    print(f"Saved checkpoint: {STATE_FILE}")
    print(f"Phase: {state['phase']} | Status: {state['status']}")

    # Preserve task progress even if a local chat source is temporarily unavailable.
    try:
        from export_chat import refresh_archives

        conversations = refresh_archives()
        if conversations:
            print(f"Refreshed {conversations} local conversation archive(s).")
    except (OSError, ValueError, StopIteration) as error:
        print(f"Checkpoint saved; chat archive refresh failed: {error}", file=sys.stderr)


if __name__ == "__main__":
    main()
